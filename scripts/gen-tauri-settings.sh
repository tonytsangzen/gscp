#!/usr/bin/env bash
# 生成 gen/android/tauri.settings.gradle 与 app/tauri.properties（后者仅缺失时）。
#
# 两个文件都由 tauri CLI 在 `tauri android build` 时生成；本项目定制了 BuildTask.kt
# 直接调用 cargo，绕过 CLI，因此需要在 gradle 之前自行生成。
# - tauri.settings.gradle：把 settings.gradle 里的 :tauri-android 指向 cargo registry 中
#   tauri crate 自带的 mobile/android Gradle 工程。
# - app/tauri.properties：versionName/versionCode（app/build.gradle.kts 读取）；缺失时
#   gradle 回落 versionName=1.0/versionCode=1，CI 打出的包会低版本且无法覆盖安装
#   （2026-10-14 CI 包缺失导致 AR 闪退 + 版本号错误的教训）。本地已有则不覆盖，
#   保留本地手动调过的 versionCode。
set -euo pipefail
cd "$(dirname "$0")/.."

CARGO_HOME_DIR="${CARGO_HOME:-$HOME/.cargo}"

# 从 Cargo.lock 解析锁定的 tauri 版本
TAURI_VER=$(awk '/^name = "tauri"$/{getline; sub(/version = /, ""); gsub(/"/, ""); print; exit}' Cargo.lock)
if [ -z "$TAURI_VER" ]; then
  echo "错误：未能从 Cargo.lock 解析 tauri 版本" >&2
  exit 1
fi

# 定位 registry 源码目录（需先执行过一次 cargo build/fetch 以解包源码）
DIR=$(ls -d "$CARGO_HOME_DIR"/registry/src/*/tauri-"$TAURI_VER"/mobile/android 2>/dev/null | head -n1 || true)
if [ -z "$DIR" ]; then
  echo "错误：未找到 tauri $TAURI_VER 的 registry 源码目录。请先执行一次 cargo build（如 cargo fetch 后构建）。" >&2
  exit 1
fi

OUT="crates/gscp-app/gen/android/tauri.settings.gradle"
mkdir -p "$(dirname "$OUT")"
cat > "$OUT" <<EOF
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
include ':tauri-android'
project(':tauri-android').projectDir = new File("$DIR")
EOF
echo "已生成 $OUT -> $DIR"

# ── app/tauri.properties（versionName/versionCode，仅缺失时生成）──────────
PROPS="crates/gscp-app/gen/android/app/tauri.properties"
if [[ -f "$PROPS" ]]; then
  echo "已存在 ${PROPS}，跳过"
else
  VERSION=$(sed -n 's/^version = "\(.*\)"/\1/p' Cargo.toml | head -n1)
  [[ -n "$VERSION" ]] || { echo "错误：未能从 Cargo.toml 解析 version" >&2; exit 1; }
  # versionCode 方案：major*10000 + minor*100 + patch（忽略 prerelease 后缀）
  IFS='.-' read -r VMAJOR VMINOR VPATCH _ <<<"$VERSION"
  VCODE=$((VMAJOR * 10000 + VMINOR * 100 + ${VPATCH:-0}))
  mkdir -p "$(dirname "$PROPS")"
  cat > "$PROPS" <<EOF
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
tauri.android.versionName=$VERSION
tauri.android.versionCode=$VCODE
EOF
  echo "已生成 $PROPS (versionName=$VERSION versionCode=$VCODE)"
fi
